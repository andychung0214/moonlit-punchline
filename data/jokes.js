export const JOKES = Object.freeze(
  JOKE_CATEGORIES.flatMap(({ id }) =>
    SOURCE[id].map(([question, answer, distractors, note, region, difficulty], index) =>
      Object.freeze({
        id: `${id}-${String(index + 1).padStart(3, '0')}`,
        category: id,
        question,
        answer,
        distractors: Object.freeze([...distractors]),
        region,
        note,
        difficulty
      })
    )
  )
);
